def _fill_appendix() -> str:
    """把版本号与实际路径填进附录。

    为什么必须动态填（实测问题）：
        %APPDATA% 不可写时，程序会自动回退到其它数据目录。
        若附录里写死 "%APPDATA%\\EcoTidy"，用户按说明去找会找不到文件。
        这里统一取运行时真实值，永远与程序行为一致。
    """
    from utils import paths

    data_dir = str(paths.DATA_DIR)
    return (APPENDIX
            .replace("{app_name}", paths.APP_NAME)
            .replace("{version}", paths.VERSION)
            .replace("{data_dir}", data_dir)
            .replace("{tasks_dir}", str(paths.TASKS_DIR) + "\\")
            .replace("{log_path}", str(paths.ERROR_LOG_PATH))
            .replace("{export_dir}", str(paths.EXPORT_DIR)))


# 章节键名 -> 内容。
# 注意：appendix 存的是**函数**而不是字符串 —— 里面的路径必须在"打开帮助时"
# 才取值。若在模块导入时就拼好，一旦数据目录在运行期发生变化（或测试里被
# 指到临时目录），帮助里显示的就会是过时的旧路径（实测踩坑）。
CONTENT = {
    "quickstart": QUICKSTART,
    "data": DATA_REQUIREMENTS,
    "terms": TERMS,
    "faq": FAQ,
    "glossary": GLOSSARY,
    "appendix": _fill_appendix,
}

# 章节键名 -> 左侧目录标题（供 help_panel 直接使用，避免两处不一致）
SECTION_TITLES = dict(SECTIONS)


def section(section_key: str) -> str:
    """按章节键名取内容；未知键名返回提示文案而不是抛异常（避免 F1 直接崩）。

    内容可以是字符串，也可以是"返回字符串的函数"（appendix 就是函数，
    因为里面的路径要按打开帮助那一刻的真实值生成）。
    """
    content = CONTENT.get(section_key)
    if content is None:
        return "<p>该章节暂未编写。</p>"
    if callable(content):
        try:
            return content()
        except Exception:  # noqa: BLE001 - 帮助内容生成失败不该让 F1 崩溃
            return "<p>该章节暂时无法显示。</p>"
    return content


def title(section_key: str) -> str:
    """按章节键名取目录标题。"""
    return SECTION_TITLES.get(section_key, section_key)


def page_section(page_index: int) -> str:
    """页面序号 -> 该页对应的帮助章节键名。"""
    return PAGE_HELP_MAP.get(page_index, "quickstart")

