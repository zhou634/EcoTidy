# 五、指标公式速查（阶段 4 交付）
# ---------------------------------------------------------------------------
# 说明：本节内容由 core/eco_index.py 的 METRIC_DESCRIPTIONS 动态生成，
# 保证"帮助面板里的公式"与"指标表里鼠标悬浮看到的公式"永远一致（方案 5.6）。
def _metrics_table() -> str:
    """由 core.eco_index 的指标说明实时生成"指标公式速查"表格。

    为什么动态生成而不是手写第二份：
        指标说明必须与"指标列悬浮提示"完全一致。若帮助面板里另写一份文案，
        两处一旦不同步，用户会看到互相矛盾的解释。
        引用失败时退回内置文案，保证帮助面板永远可用。
    """
    try:
        from core import eco_index
    except Exception:  # pragma: no cover - 依赖异常时帮助面板仍要能用
        return _FALLBACK_METRICS_TABLE

    rows: list = []
    for column in list(eco_index.ROW_METRIC_COLUMNS) + list(eco_index.SUMMARY_METRIC_COLUMNS):
        description = eco_index.METRIC_DESCRIPTIONS.get(column, "")
        if not description:
            continue
        # 指标名统一取列名的短名（"H 香农指数" → "香农指数"），
        # 说明文字整体作为"公式/含义"一栏 —— 不要从说明里反推名字：
        # 有些说明（如"S 物种数"）本身不含 " = "，反推会把整段说明当成名字。
        parts = column.split(" ", 1)
        name = parts[1] if len(parts) == 2 and len(parts[0]) <= 2 else column
        rows.append("<tr><td>{0}</td><td>{1}</td></tr>".format(name, description))
    if not rows:
        return _FALLBACK_METRICS_TABLE
    return ("<h4>软件计算的全部指标（与指标表里的悬浮提示同一份说明）</h4>\n"
            "<table><tr><th>指标</th><th>公式</th></tr>\n{0}\n</table>".format("\n".join(rows)))


